#!/usr/bin/env python3
"""hpp_pilot.py -- pilot stand-in for the DECOMP-1 hpp registry.

DECOMP-1 owns symbol declaration (rule 1).  Until its gen_hpp.py declares
non-vtable methods and multi-width member views, this module synthesizes the
MINIMAL hpp each pilot cpp compiles against, from exactly the same registry
JSON + the converter's ClassView ledger (i.e. the hpp mirrors what the
converter used -- never the other way round).

Emission:
  * one hpp per class (rule 2: <Name>.hpp <-> <Name>.cpp)
  * members at true offsets with explicit gap pads (layout-faithful at the
    offsets the pilot touches; tail pad to registry size when known)
  * multi-view offsets emit anonymous unions (word/dword/ptr evidence views)
  * method declarations matching the converter's emitted signatures exactly
"""
import re

from passes import WIDTH_OF, spell_type, ERA_TYPE_NAMES


def guard_of(cls):
    return "DECOMP_PILOT_" + re.sub(r"[^A-Za-z0-9]", "_", cls).upper() + "_HPP"


def cls_ident(cls):
    """C++-safe class identifier ('Nested@Inner' RTTI names -> '_')."""
    return re.sub(r"[^A-Za-z0-9_]", "_", cls or "Unnamed")


def _pad(off_from, off_to):
    if off_to <= off_from:
        return []
    return ["    char __pad_%03X[%d];  // 0x%03X" % (off_from, off_to - off_from,
                                                     off_from)]


def gen_class_hpp(cls, views, sigs, registry_size, extra_notes=(),
                  used_globals=None, extra_externs=None, extra_fwd=None):
    """views: ClassView; sigs: list of emitted signature dicts for this class.

    sigs may include callee pseudo-sigs (R3 non-leaf support): records with
    `_callee` mark methods declared-only (called from another unit class's
    body) -- they render identically (a declaration line).
    extra_externs: full `extern RET name(args);` lines for global callees.
    """
    scal = views.scalars.get(cls, {})
    arrs = views.arrays.get(cls, {})
    vts = views.virtuals.get(cls, {})
    offs = sorted(set(list(scal.keys()) + list(arrs.keys())))

    lines = []
    lines.append("// GENERATED by tools/decomp_sys/hpp_pilot.py -- pilot stand-in")
    lines.append("// registry hpp (DECOMP-1 will own this once gen_hpp.py covers")
    lines.append("// non-vtable methods + multi-width views).  DO NOT EDIT.")
    for n in extra_notes:
        lines.append("// %s" % n)

    # forward declarations for class-typed pointer members / param types
    # (undeclared class names in member decls were C2143 batch failures)
    fwd = set()

    def _fwd_ok(n):
        """CW2: only bare, declarable class names get `class X;`.

        Rejects: primitives, era_types.h names (LONG/HWND/... -- declaring
        `class LONG;` turned `volatile LONG *` into `volatile class LONG *`
        -> C2664), qualified/nested spellings (`A::B;` is C2143), and any
        spelling carrying IDA decoration.
        """
        if not n:
            return False
        n = n.strip()
        if n in _PRIM_TYPES or n in WIDTH_OF or n in ERA_TYPE_NAMES:
            return False
        if not re.match(r"^[A-Za-z_]\w*$", n):
            return False
        if n == cls_ident(cls):
            return False
        return True

    for off in offs:
        arr = arrs.get(off)
        if arr and not _is_prim(arr["elem"]) and not arr["elem"].endswith("*"):
            if _fwd_ok(arr["elem"]):
                fwd.add(arr["elem"])
        for v in scal.get(off, {}).values():
            b = (v.get("type") or "").replace("*", "").strip()
            if v.get("type", "").endswith("*") and b and not _is_prim(b):
                if _fwd_ok(b):
                    fwd.add(b)
    for s in sigs:
        if s["ret"].endswith("*"):
            b = s["ret"].replace("*", "").strip()
            if b and not _is_prim(b):
                if _fwd_ok(b):
                    fwd.add(b)
        for t, _n in s["params_spelled"]:
            if t.endswith("*"):
                b = t.replace("*", "").strip()
                if b and not _is_prim(b):
                    if _fwd_ok(b):
                        fwd.add(b)
    if extra_fwd:
        # R4: cast-only class references in the emitted bodies
        # ((AnimClass *)x) need a forward declaration; the member/param
        # scan above never sees them (C2065 AnimClass family).
        for n in extra_fwd:
            if _fwd_ok(n):
                fwd.add(n)
    # CW2: extern-block return/param types (`extern Coord3D * __fastcall
    # f(...)`) were never scanned -- `Coord3D` then hit C2143 "missing ';'
    # before '*'" on the declaration itself (18 census units).
    for d in (extra_externs or []):
        body = d.replace("extern", " ", 1)
        for m in re.finditer(r"\b([A-Za-z_]\w*)\s*\*", body):
            if _fwd_ok(m.group(1)):
                fwd.add(m.group(1))
    # R5: class-typed globals (`extern Stream * g_ZBufferDescriptor`) --
    # the type names an undeclared class (C2143 BlitTrans hpp family).
    # COLLISION: a global VARIABLE whose name equals a class name (the
    # registry global `Stream` vs class `Stream`) makes the fwd decl and
    # the extern fight -- degrade the global's type to void * instead.
    if used_globals:
        gnames = set(used_globals)
        for name in list(used_globals):
            ty = used_globals[name]
            if ty.endswith("*"):
                b = ty.replace("*", "").strip()
                if b and not _is_prim(b):
                    if b in gnames:
                        # class name == sibling global name: degrade
                        used_globals[name] = "void *"
                        continue
                    if _fwd_ok(b):
                        fwd.add(b)
        fwd -= gnames
    fwd.discard(cls_ident(cls))
    if fwd:
        lines.append("// forward declarations")
        lines.extend("class %s;" % f for f in sorted(fwd))
        lines.append("")

    lines.append("#ifndef %s" % guard_of(cls))
    lines.append("#define %s" % guard_of(cls))
    lines.append("")
    lines.append('#include "era_types.h"  // CW2: Win32/IDA type aliases (types only)')
    lines.append("#include <string.h>   // memset (whole-object zero init)")
    lines.append("#include <stdlib.h>   // qsort/abs/atoi (CRT calls in bodies)")
    lines.append("#include <stdio.h>    // sprintf/sscanf/printf (R5)")
    lines.append("#include <math.h>     // fabs/sqrt/pow (CW2: bodies call them)")
    lines.append("#include <stdarg.h>   // va_list (R5)")
    lines.append("")
    lines.append("class %s" % cls_ident(cls))
    lines.append("{")
    lines.append("public:")

    cursor = 0
    emitted_names = set()

    def entries_of(off):
        arr = arrs.get(off)
        roles = scal.get(off, {})
        entries = []          # full declaration strings (sans indent)
        if arr:
            elem = spell_type(arr["elem"])
            if arr["count"] > 0:
                entries.append("%s %s[%d];" % (elem, arr["name"],
                                                arr["count"]))
            else:
                # unknown-count element view: 1-element carrier (VC6 rejects
                # `T x[];` members with C2133; indexing past [0] compiles)
                entries.append("%s %s[1];  /* element view */"
                               % (elem, arr["name"]))
            emitted_names.add(arr["name"])
        for role in ("byte", "word", "dword", "qword", "ptr"):
            v = roles.get(role)
            if not v:
                continue
            nm = v["name"]
            if nm in emitted_names:
                nm = nm + "_" + role
            entries.append("%s %s;" % (spell_type(v["type"]), nm))
            emitted_names.add(nm)
        return entries

    # R4: overlapping views (a dword member at 0xC plus a byte member at
    # 0xD -- IsAllocated family) must become a union, not a skipped offset:
    # `if off < cursor: continue` silently dropped the narrow view and the
    # body referenced a member the hpp never declared (C2039).
    groups = []
    for off in offs:
        span = max(1, _view_span(scal.get(off, {}), arrs.get(off)))
        if groups and off < groups[-1]["end"]:
            g = groups[-1]
            g["offs"].append(off)
            g["end"] = max(g["end"], off + span)
        else:
            groups.append({"base": off, "end": off + span, "offs": [off]})
    for g in groups:
        off0 = g["base"]
        lines.extend(_pad(cursor, off0))
        entries = []
        for off in g["offs"]:
            entries.extend(entries_of(off))
        if len(g["offs"]) > 1:
            total = max(1, g["end"] - off0)
            lines.append("    union {  // overlapping views @0x%03X" % off0)
            for e in entries:
                lines.append("        " + e)
            lines.append("        char __pad_union_%03X[%d];"
                         % (off0, total))
            lines.append("    };")
        elif len(entries) > 1:
            lines.append("    union {  // multi-evidence view @0x%03X" % off0)
            for e in entries:
                lines.append("        " + e)
            lines.append("    };")
        elif entries:
            lines.append("    " + entries[0] + "  // 0x%03X" % off0)
        cursor = g["end"]

    # vtable-authority virtuals (dispatch upgrades)
    for slot in sorted(vts):
        v = vts[slot]
        lines.append("    virtual void %s();  // slot %d (%s) [authority]"
                     % (v["name"], slot, v.get("proto") or "")[:120])

    if registry_size and cursor < registry_size:
        lines.extend(_pad(cursor, registry_size))
        lines.append("")
        lines.append("    // DECOMP_SIZECHECK(%s, %s, %d);" % (cls, cls,
                                                              registry_size))

    # method declarations (exactly the converter-emitted signatures)
    lines.append("")
    lines.append("    // ---- pilot methods (registry signatures)")
    for s in sigs:
        if s.get("free"):
            # R4 cdecl arbitration: emitted at global scope; the prototype
            # rides the unit's extern block, not the class body.
            continue
        cc = {"__fastcall": " __fastcall",
              "__stdcall": " __stdcall"}.get(s.get("cc"), "")
        # Audit-rem ①: this-as-id functions are emitted as STATIC
        # __fastcall members -- the int ID rides ECX exactly like the
        # original receiver slot did.
        static = "static " if s.get("this_as_id") else ""
        # R5: VC6 rejects `__thiscall` as a declaration keyword (C4234);
        # callee pseudo-sigs can carry it inside param/ret spellings
        ret = (s["ret"] or "int").replace("__thiscall", "__stdcall")
        params = [(t.replace("__thiscall", "__stdcall"), n)
                  for t, n in s["params_spelled"]]
        lines.append("    %s%s%s %s(%s);  // 0x%s" % (
            static, ret, cc, s["method"], ", ".join(
                "%s %s" % (t, n) for t, n in params),
            s["addr"][2:].upper().lstrip("0").zfill(6)))
    lines.append("};")
    lines.append("")
    if used_globals:
        lines.append("// ---- globals used by this unit (registry names)")
        for name in sorted(used_globals):
            ty = used_globals[name]
            if ty.endswith("[]"):
                # R5 struct globals: byte-arithmetic carrier
                lines.append("extern %s %s[];" % (ty[:-2], name))
            else:
                lines.append("extern %s %s;" % (ty, name))
        lines.append("")
    if extra_externs:
        lines.append("// ---- global callee prototypes (R3 non-leaf)")
        for d in extra_externs:
            lines.append(d.replace("__thiscall", "__stdcall"))
        lines.append("")
    lines.append("#endif  // %s" % guard_of(cls))
    lines.append("")
    return "\n".join(lines), emitted_names


def gen_free_hpp(unit, extra_notes=(), used_globals=None, extra_externs=None,
                 extra_fwd=None):
    """Extern-only unit hpp for a translation unit with NO class shells.

    NO_CLS global functions are emitted at file scope (no owning class);
    the cpp still `#include "<unit>.hpp"`, so the unit needs a mirror hpp
    carrying the same guard/include/extern contract gen_class_hpp gives a
    class-bearing unit -- just without a `class {...};` block.
    """
    guard = "DECOMP_PILOT_" + re.sub(r"[^A-Za-z0-9]", "_", unit).upper() \
        + "_HPP"
    lines = []
    lines.append("// GENERATED by tools/decomp_sys/hpp_pilot.py -- pilot "
                 "stand-in")
    lines.append("// global-function unit (NO_CLS free shell: no owning "
                 "class).  DO NOT EDIT.")
    for n in extra_notes:
        lines.append("// %s" % n)

    fwd = set()

    def _fwd_ok_free(n):
        """CW2: same gate as gen_class_hpp -- bare, declarable names only."""
        if not n:
            return False
        n = n.strip()
        if n in _PRIM_TYPES or n in WIDTH_OF or n in ERA_TYPE_NAMES:
            return False
        return bool(re.match(r"^[A-Za-z_]\w*$", n))

    if extra_fwd:
        for n in extra_fwd:
            if _fwd_ok_free(n):
                fwd.add(n)
    if used_globals:
        gnames = set(used_globals)
        for name in list(used_globals):
            ty = used_globals[name]
            if ty.endswith("*"):
                b = ty.replace("*", "").strip()
                if b and not _is_prim(b):
                    if b in gnames:
                        used_globals[name] = "void *"
                        continue
                    if _fwd_ok_free(b):
                        fwd.add(b)
        fwd -= gnames
    # CW2: extern-block return types (`extern Coord3D * __fastcall f(...)`)
    # are never scanned by the member/param walk -- the undeclared return
    # class was C2143 "missing ';' before '*'" on the declaration itself.
    for d in (extra_externs or []):
        body = d.replace("extern", " ", 1)
        for m in re.finditer(r"\b([A-Za-z_]\w*)\s*\*", body):
            if _fwd_ok_free(m.group(1)):
                fwd.add(m.group(1))
    if fwd:
        lines.append("// forward declarations")
        lines.extend("class %s;" % f for f in sorted(fwd))
        lines.append("")

    lines.append("#ifndef %s" % guard)
    lines.append("#define %s" % guard)
    lines.append("")
    lines.append('#include "era_types.h"  // CW2: Win32/IDA type aliases (types only)')
    lines.append("#include <string.h>   // memset (whole-object zero init)")
    lines.append("#include <stdlib.h>   // qsort/abs/atoi (CRT calls in bodies)")
    lines.append("#include <stdio.h>    // sprintf/sscanf/printf (R5)")
    lines.append("#include <math.h>     // fabs/sqrt/pow (CW2: bodies call them)")
    lines.append("#include <stdarg.h>   // va_list (R5)")
    lines.append("")
    if used_globals:
        lines.append("// ---- globals used by this unit (registry names)")
        for name in sorted(used_globals):
            ty = used_globals[name]
            if ty.endswith("[]"):
                lines.append("extern %s %s[];" % (ty[:-2], name))
            else:
                lines.append("extern %s %s;" % (ty, name))
        lines.append("")
    if extra_externs:
        lines.append("// ---- global callee prototypes (R3 non-leaf)")
        for d in extra_externs:
            lines.append(d.replace("__thiscall", "__stdcall"))
        lines.append("")
    lines.append("#endif  // %s" % guard)
    lines.append("")
    return "\n".join(lines)


_PRIM_TYPES = {
    "void", "int", "unsigned int", "short", "unsigned short", "char",
    "signed char", "unsigned char", "bool", "float", "double", "long",
    "unsigned long", "__int64", "unsigned __int64", "wchar_t",
}


def _is_prim(ty):
    t = (ty or "").strip()
    if t in _PRIM_TYPES:
        return True
    # R3: only a bare identifier can be forward-declared.  Qualified /
    # keyword-prefixed spellings ("const void", "const wchar_t") are not
    # class names -- `class const void;`/`class const wchar_t;` were hard
    # compile failures (C2628 '$S1' followed by 'void', C2079 wchar_t
    # uses undefined class) that poisoned whole units.
    return not re.match(r"^[A-Za-z_]\w*$", t)


def _view_span(roles, arr):
    if arr and arr.get("count"):
        return arr["count"] * WIDTH_OF.get(arr["elem"], 4)
    if arr:
        return 4
    if roles:
        # R4: the span that advances the hpp cursor must be the width of the
        # DECLARATION actually emitted (`T name;`), not the registry record's
        # byte span.  A pad/unknown record carrying width 13 for an `int`
        # slot swallowed the members at +4/+8/+0xC (C2039 m004 family).
        spans = []
        for v in roles.values():
            ty = v.get("type") or ""
            if ty.endswith("*"):
                spans.append(4)          # x86 pointer
            else:
                spans.append(WIDTH_OF.get(ty) or min(int(v.get("width", 4) or 4),
                                                     4))
        return max(1, max(spans))
    return 4
