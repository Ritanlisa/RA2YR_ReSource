#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
gen_theater.py -- byte-exact reproduction of the TheaterClass descriptor table
at .rdata 0x3E1B78..0x3E1E18 in the original gamemd.exe (6 entries x 0x70B).

Struct layout (reverse-engineered from the byte dump):
  +0x00 char  name[16]    "TEMPERATE"
  +0x10 char  display[32] "Name:Temperate"
  +0x30 char  ini[10]     "TEMPERAT"
  +0x3A char  iso[10]     "ISOTEMP"
  +0x44 char  iso2[10]    "ISOTEM"
  +0x4E char  ext[4]      "TEM"
  +0x52 char  mmt[4]      "MMT"
  +0x56 char  letter[2]   "T"
  +0x58 float f1          1.0
  +0x5C float f2          0.4
  +0x60 int   i1          0
  +0x64 float f3          1.875
  +0x68 int   i2          -1
  +0x6C int   i3          0
Generated C: extern-visible const array; compile with era cl, link, then
compare_bytes.py diffs our table vs original.
"""
import struct, sys

ORIG = r"D:\RA2MD\gamemd.exe"
BASE = 0x3E1B78
COUNT = 6
STRIDE = 0x70

FIELDS = [
    ("name",   0x00, 16, "s"), ("display", 0x10, 32, "s"),
    ("ini",    0x30, 10, "s"), ("iso",     0x3A, 10, "s"),
    ("iso2",   0x44, 10, "s"), ("ext",     0x4E, 4,  "s"),
    ("mmt",    0x52, 4,  "s"), ("letter",  0x56, 2,  "s"),
    ("f1",     0x58, 4, "f"), ("f2",      0x5C, 4, "f"),
    ("i1",     0x60, 4, "i"), ("f3",      0x64, 4, "f"),
    ("i2",     0x68, 4, "i"), ("i3",      0x6C, 4, "i"),
]

def cstr(bs):
    # bytes up to NUL
    z = bs.find(b"\x00")
    s = bs[:z if z >= 0 else len(bs)].decode("latin1")
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

def cfmt(v):
    # shortest exact repr for floats from the binary (always with a decimal point)
    for cand in (f"{v:g}", f"{v:.6f}", f"{v:.9g}"):
        if struct.unpack("<f", struct.pack("<f", float(cand)))[0] == v:
            if "." not in cand and "e" not in cand and "E" not in cand:
                cand += ".0"
            return cand + "f"
    return f"{v!r}f"

def main():
    b = open(ORIG, "rb").read()
    entries = []
    for e in range(COUNT):
        base = BASE + e * STRIDE
        rec = {}
        for name, off, size, kind in FIELDS:
            raw = b[base+off:base+off+size]
            if kind == "s":
                rec[name] = cstr(raw)
            elif kind == "f":
                rec[name] = struct.unpack("<f", raw)[0]
            else:
                rec[name] = struct.unpack("<i", raw)[0]
        entries.append(rec)
    L = []
    L.append("/* generated by gen_theater.py -- TheaterClass descriptor table */")
    L.append("struct TheaterData {")
    for name, off, size, kind in FIELDS:
        t = f"char {name}[{size}];" if kind == "s" else (
            f"float {name};" if kind == "f" else f"int {name};")
        L.append(f"    {t}  /* +0x{off:02X} */")
    L.append("};")
    L.append("")
    L.append("struct TheaterData const g_theaterTable[6] = {")
    for rec in entries:
        parts = []
        for name, off, size, kind in FIELDS:
            if kind == "s":
                parts.append(rec[name])
            elif kind == "f":
                parts.append(cfmt(rec[name]))
            else:
                parts.append(str(rec[name]))
        L.append("    {" + ", ".join(parts) + "},")
    L.append("};")
    open("tools/data_match/w1/theater.c", "w").write("\n".join(L))
    print("wrote theater.c with", len(entries), "entries")

if __name__ == "__main__":
    main()
