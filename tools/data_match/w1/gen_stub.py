#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
gen_stub.py -- generate ref.asm + main.c for the .idata alignment link test.

Reference strategy (experiment 1):
  - one ref object (ref.asm) referencing imports in ORIGINAL POOL order:
    DLL groups in descriptor order; within a DLL, hint/name entries sorted by
    their file offset in the original pool (= original emission order).
  - KERNEL32: only the first pool batch (103 game-pass names; hn_off < dllname
    offset 0x40FF8E). The CRT batch (59) must come from libcmt.lib itself.
  - ordinal-only DLLs (OLEAUT32/WSOCK32/DSOUND/COMCTL32@17): reference lib
    symbols resolved by (dll, ordinal) from lib_members.json, in INT order.
"""
import json, os, sys

W1 = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(W1, "..", "..", ".."))
ORIG = json.load(open(os.path.join(ROOT, ".omo/agents/datamatch/orig_imports.json"), encoding="utf-8"))
LIBS = json.load(open(os.path.join(ROOT, ".omo/agents/datamatch/lib_members.json"), encoding="utf-8"))

K32_NAME_OFF = 0x40FF8E  # file offset of "KERNEL32.dll" name string

def libkey(dll):
    m = {"KERNEL32.dll": "kernel32", "USER32.dll": "user32", "GDI32.dll": "gdi32",
         "ADVAPI32.dll": "advapi32", "SHELL32.dll": "shell32", "ole32.dll": "ole32",
         "OLEAUT32.dll": "oleaut32", "WINMM.dll": "winmm", "WSOCK32.dll": "wsock32",
         "DDRAW.dll": "ddraw", "DSOUND.dll": "dsound", "VERSION.dll": "version",
         "COMCTL32.dll": "comctl32", "IMM32.dll": "imm32", "binkw32.dll": "binkw32"}
    base = m[dll]
    for k in LIBS:
        if k.replace("\\", "/").endswith(f"/{base}.lib"):
            return k
    raise KeyError(base)

def members(dll):
    return LIBS[libkey(dll)]

def sym_by_name(dll, hn_name):
    for m in members(dll):
        if m["mode"] == "NAME" and m["import_name"] == hn_name:
            return m["sym"]
    # bink fallback: lib/def double-underscore symbol
    cand = "_" + hn_name
    for m in members(dll):
        if m["sym"] == cand:
            return cand
    return None

def sym_by_ordinal(dll, o):
    for m in members(dll):
        if m["mode"] == "ORD" and m["ordinal"] == o:
            return m["sym"].replace("__imp_", "")
    return None

def main():
    ref_syms = []   # ordered (dll, sym, tag)
    problems = []
    for d in ORIG["descs"]:
        dll = d["dll"]
        # named entries in pool order
        named = [f for f in d["funcs"] if "name" in f]
        named.sort(key=lambda f: f["hn_off"])
        if dll == "KERNEL32.dll":
            named = [f for f in named if f["hn_off"] < K32_NAME_OFF]
        for f in named:
            s = sym_by_name(dll, f["name"])
            if s is None:
                problems.append((dll, f["name"], "no name member"))
                continue
            ref_syms.append((dll, s, f["name"]))
        # ordinal entries (OLEAUT32/WSOCK32/DSOUND fully ordinal; COMCTL32 one)
        ord_funcs = [f for f in d["funcs"] if "ordinal" in f]
        if dll == "KERNEL32.dll":
            ord_funcs = []  # CRT batch: let libcmt pull these
        for f in ord_funcs:
            s = sym_by_ordinal(dll, f["ordinal"])
            if s is None:
                problems.append((dll, f["ordinal"], "no ord member"))
                continue
            ref_syms.append((dll, s, f"@{f['ordinal']}"))
    if problems:
        print("PROBLEMS:")
        for p in problems:
            print("  ", p)
        sys.exit(1)

    seen = set()
    uniq = []
    for t in ref_syms:
        if t[1] in seen:
            print(f"  dup skipped: {t[1]}")
            continue
        seen.add(t[1])
        uniq.append(t)
    print(f"{len(uniq)} unique references across {len(ORIG['descs'])} DLLs")

    lines = ["; generated by gen_stub.py -- do not edit",
             "        .386",
             "        .model flat",
             ""]
    for dll, s, tag in uniq:
        lines.append(f"        extrn {s}:proc   ; {dll} {tag}")
    lines.append("")
    lines.append("        .data")
    lines.append("        public _refTable")
    lines.append("_refTable   label dword")
    for dll, s, tag in uniq:
        lines.append(f"        dd  {s}")
    lines.append("")
    lines.append("        end")
    with open(os.path.join(W1, "ref.asm"), "w") as f:
        f.write("\n".join(lines))

    with open(os.path.join(W1, "main.c"), "w") as f:
        f.write("""/* generated by gen_stub.py */
extern unsigned long _refTable[];
int __stdcall WinMain(void *hInst, void *hPrev, char *cmdLine, int show)
{
    (void)hInst; (void)hPrev; (void)cmdLine; (void)show;
    return (int)(_refTable[0] & 0);
}
""")
    print("wrote ref.asm / main.c")

if __name__ == "__main__":
    main()
