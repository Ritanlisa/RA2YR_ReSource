#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
gen_stub2.py -- v2 reference stub generator.

Changes vs v1:
  - prefer non-__imp_ thunk symbols (fixes COMCTL32 picking __imp_ variants)
  - KERNEL32: reference the FULL 162 in original pool order (wave1 run order,
    then wave2/CRT run order). Two build variants:
      test2: all references in ref.obj (single wave)
      test3: ref1.obj = wave1 refs; ref2.lib(ref2.obj) = CRT-batch refs,
             linked AFTER libcmt.lib to land in a later lib-scan wave.
"""
import json, os, sys, subprocess

W1 = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(W1, "..", "..", ".."))
ORIG = json.load(open(os.path.join(ROOT, ".omo/agents/datamatch/orig_imports.json"), encoding="utf-8"))
LIBS = json.load(open(os.path.join(ROOT, ".omo/agents/datamatch/lib_members.json"), encoding="utf-8"))
K32_NAME_OFF = 0x40FF8E

def members(dll):
    m = {"KERNEL32.dll": "kernel32", "USER32.dll": "user32", "GDI32.dll": "gdi32",
         "ADVAPI32.dll": "advapi32", "SHELL32.dll": "shell32", "ole32.dll": "ole32",
         "OLEAUT32.dll": "oleaut32", "WINMM.dll": "winmm", "WSOCK32.dll": "wsock32",
         "DDRAW.dll": "ddraw", "DSOUND.dll": "dsound", "VERSION.dll": "version",
         "COMCTL32.dll": "comctl32", "IMM32.dll": "imm32", "binkw32.dll": "binkw32"}
    base = m[dll]
    for k in LIBS:
        if k.replace("\\", "/").endswith(f"/{base}.lib"):
            return LIBS[k]
    raise KeyError(base)

def sym_by_name(dll, hn):
    cands = [x for x in members(dll) if x["mode"] == "NAME" and x["import_name"] == hn]
    if not cands:
        c = "_" + hn
        return c if any(x["sym"] == c for x in members(dll)) else None
    plain = [x for x in cands if not x["sym"].startswith("__imp_")]
    return (plain or cands)[0]["sym"]

def sym_by_ord(dll, o):
    for x in members(dll):
        if x["mode"] == "ORD" and x["ordinal"] == o:
            s = x["sym"]
            return s[6:] if s.startswith("__imp_") else s
    return None

def write_asm(path, refs, label="_refTable"):
    lines = ["; generated by gen_stub2.py", "        .386", "        .model flat", ""]
    for dll, s, tag in refs:
        lines.append(f"        extrn {s}:proc   ; {dll} {tag}")
    lines += ["", "        .data", f"        public {label}", f"{label}   label dword"]
    lines += [f"        dd  {s}" for _, s, _ in refs]
    lines += ["", "        end"]
    open(path, "w").write("\n".join(lines))

def main():
    wave1, wave2 = [], []
    for d in ORIG["descs"]:
        dll = d["dll"]
        named = sorted([f for f in d["funcs"] if "name" in f], key=lambda f: f["hn_off"])
        for f in named:
            s = sym_by_name(dll, f["name"])
            assert s, (dll, f["name"])
            if dll == "KERNEL32.dll":
                (wave1 if f["hn_off"] < K32_NAME_OFF else wave2).append((dll, s, f["name"]))
            else:
                wave1.append((dll, s, f["name"]))
        for f in [x for x in d["funcs"] if "ordinal" in x]:
            if dll == "KERNEL32.dll":
                continue  # CRT batch is covered by wave2 names? ordinals in K32: none
            s = sym_by_ord(dll, f["ordinal"])
            assert s, (dll, f["ordinal"])
            wave1.append((dll, s, f"@{f['ordinal']}"))
    print(f"wave1={len(wave1)} wave2(K32 CRT)={len(wave2)}")
    # test2: single object, both labels
    L = ["; generated by gen_stub2.py", "        .386", "        .model flat", ""]
    for dll, s, tag in wave1 + wave2:
        L.append(f"        extrn {s}:proc   ; {dll} {tag}")
    L += ["", "        .data", "        public _refTable", "        public _refTable2",
          "_refTable    label dword"]
    L += [f"        dd  {s}" for _, s, _ in wave1]
    L += ["_refTable2   label dword"]
    L += [f"        dd  {s}" for _, s, _ in wave2]
    L += ["", "        end"]
    open(os.path.join(W1, "ref.asm"), "w").write("\n".join(L))
    write_asm(os.path.join(W1, "ref1.asm"), wave1)                      # test3 part A
    write_asm(os.path.join(W1, "ref2.asm"), wave2, "_refTable2")        # test3 part B
    with open(os.path.join(W1, "main.c"), "w") as f:
        f.write("""/* generated by gen_stub2.py */
extern unsigned long refTable[];   /* -> symbol _refTable  (MASM label) */
extern unsigned long refTable2[];  /* -> symbol _refTable2 (MASM label) */
int __stdcall WinMain(void *hInst, void *hPrev, char *cmdLine, int show)
{
    (void)hInst; (void)hPrev; (void)cmdLine; (void)show;
    return (int)(refTable[0] ^ refTable2[0]);
}
""")
    print("wrote ref.asm / ref1.asm / ref2.asm / main.c")

if __name__ == "__main__":
    main()
