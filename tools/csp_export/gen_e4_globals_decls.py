#!/usr/bin/env python3
"""Split e4_globals.hpp into a legacy-TU-safe declarations-only header.

Legacy TUs (gap2_defs.cpp, globals.cpp, load_options.cpp, subs_*.cpp, ...)
include e4/e4_globals.hpp for the DataGlobal_* externs. That header also
pulls _tree_full_e4.hpp + _fwd_tree_e4.hpp, whose flat class definitions
collide (C2011) with the legacy tree headers those TUs include (math.hpp
ColorStruct, utility_ext.hpp Hash/Flag/Float4/... — 127 classes).

e4_globals_decls.hpp keeps ONLY: cstdint, _fwd_tree_e4.hpp (fwd-only, no
definitions) and every extern/helper-struct line from e4_globals.hpp.
Zero class definitions -> zero cross-universe C2011.

This tool is idempotent and battery-safe: re-run after e4_globals.hpp
regenerates.

Usage: python tools/csp_export/gen_e4_globals_decls.py [--apply]
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'src' / 'e4'
FULL = SRC / 'e4_globals.hpp'
DECLS = SRC / 'e4_globals_decls.hpp'
APPLY = '--apply' in sys.argv

txt = FULL.read_text(encoding='utf-8', errors='replace')
lines = txt.split('\n')
out = [
    '// GENERATED by tools/csp_export/gen_e4_globals_decls.py -- DO NOT EDIT.',
    '// Legacy-TU-safe subset of e4_globals.hpp: externs only, NO class',
    '// definitions (cross-universe C2011 fix, G37).',
    '#pragma once',
    '#include <cstdint>',
    '#include "e4/classes/_fwd_tree_e4.hpp"',
    '',
]
n_extern = n_struct = 0
for ln in lines:
    s = ln.rstrip()
    if s.startswith('extern '):
        out.append(s)
        n_extern += 1
    elif re.match(r'^struct\s+\w+', s):
        out.append(s)
        n_struct += 1

print('externs:', n_extern, 'helper structs:', n_struct)
if APPLY:
    DECLS.write_text('\n'.join(out) + '\n', encoding='utf-8')
    print('wrote', DECLS)
else:
    print('(dry run -- pass --apply)')
