#!/usr/bin/env python3
"""Split e4_globals.hpp into a legacy-TU-safe declarations-only header.

Legacy TUs (gap2_defs.cpp, globals.cpp, load_options.cpp, subs_*.cpp, ...)
include e4/e4_globals.hpp for the DataGlobal_* externs. That header also
pulls _tree_full_e4.hpp + _fwd_tree_e4.hpp, whose flat class definitions
collide (C2011) with the legacy tree headers those TUs include (math.hpp
ColorStruct, utility_ext.hpp Hash/Flag/Float4/... — 127 classes).

e4_globals_decls.hpp keeps ONLY: cstdint, _fwd_tree_e4.hpp (fwd-only, no
definitions) and every extern/helper-struct line from e4_globals.hpp.
Zero class definitions -> zero cross-universe C2011.

This tool is idempotent and battery-safe: re-run after e4_globals.hpp
regenerates.

Usage: python tools/csp_export/gen_e4_globals_decls.py [--apply]
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'src' / 'e4'
FULL = SRC / 'e4_globals.hpp'
DECLS = SRC / 'e4_globals_decls.hpp'
APPLY = '--apply' in sys.argv

txt = FULL.read_text(encoding='utf-8', errors='replace')
lines = txt.split('\n')
out = [
    '// GENERATED by tools/csp_export/gen_e4_globals_decls.py -- DO NOT EDIT.',
    '// Legacy-TU-safe subset of e4_globals.hpp: externs only, NO class',
    '// definitions (cross-universe C2011 fix, G37).',
    '#pragma once',
    '#include <cstdint>',
    '#include "e4/classes/_fwd_tree_e4.hpp"',
    '',
]

# X25: an extern whose type is `gamemd::X *` (e4_globals.hpp carries one:
# g_RulesClass_Instance) does not resolve in the LEGACY TUs this header
# exists for -- `RulesClass` is only declared where rules.hpp is in the
# closure, and the legacy include set deliberately excludes it (C2039
# "not a member of gamemd" + C2143 cascade).  A namespace-level forward
# declaration is legal in every consumer (both universes) and makes the
# qualified pointer type resolvable; a later full definition in the same
# namespace makes it redundant-but-legal.
# X89: authoritative class/struct keyword for fwd-declared pointee types.
# `Stream` is defined as `struct Stream` in e4/classes/Stream_e4.hpp but also
# exists as a variable name (CRT FILE* at 0xAA0468) in legacy universes; the
# elaborated `struct gamemd::Stream *` declaration needs the matching keyword.
FWD_KIND = {'Stream': 'struct'}

QUALIFIED = re.compile(r'\bgamemd::(\w+)')
_KW_CACHE = {}


def _corpus_kw(ty):
    """class|struct keyword for `ty`, decided from the corpus sources."""
    if ty in FWD_KIND:
        return FWD_KIND[ty]
    if ty in _KW_CACHE:
        return _KW_CACHE[ty]
    cc = cs = 0
    for hp in (ROOT / 'src').rglob('*.hpp'):
        try:
            ht = hp.read_text(encoding='utf-8', errors='replace')
        except OSError:
            continue
        if re.search(r'\bclass\s+%s\b' % ty, ht):
            cc = 1
        elif re.search(r'\bstruct\s+%s\b' % ty, ht):
            cs = 1
        if cc and cs:
            break
    _KW_CACHE[ty] = 'struct' if (cs and not cc) else 'class'
    return _KW_CACHE[ty]


n_extern = n_struct = n_fwd = 0
fwd_done = set()
i = 0
while i < len(lines):
    s = lines[i].rstrip()
    if s.startswith('extern '):
        for ty in QUALIFIED.findall(s):
            if ty not in fwd_done:
                fwd_done.add(ty)
                out.append('')
                out.append('// X25: fwd decl for qualified extern type '
                           '(%s) -- resolves in both universes' % ty)
                out.append('namespace gamemd { %s %s; }'
                           % (_corpus_kw(ty), ty))
                n_fwd += 1
        out.append(s)
        n_extern += 1
        i += 1
    elif re.match(r'^struct\s+\w+', s):
        # copy the WHOLE struct (balanced braces) -- the line-only copy
        # truncated multi-line hosts (DSurface_ViewBounds_flat), leaving an
        # unclosed `struct X {` that swallowed every later extern as an
        # extern-storage member (C2071 storm, G42.29b).
        depth = s.count('{') - s.count('}')
        out.append(s)
        n_struct += 1
        i += 1
        while depth > 0 and i < len(lines):
            t = lines[i].rstrip()
            depth += t.count('{') - t.count('}')
            out.append(t)
            i += 1
    else:
        i += 1

print('externs:', n_extern, 'helper structs:', n_struct)
if APPLY:
    DECLS.write_text('\n'.join(out) + '\n', encoding='utf-8')
    print('wrote', DECLS)
else:
    print('(dry run -- pass --apply)')
