#!/usr/bin/env python3
"""X55 W1 shared rule: IDA backtick vftable refs -> corpus vt_ extern refs.

Single source of truth for the normalization used by BOTH:
  * tools/csp_export/rematerialize_defs.py  (future re-materialize emissions)
  * .omo/evidence/optimization/x55/x55_w1_vftable.py  (X54-touched tree fix)

IDA renders vtable references as `Cls::`vftable'' -- the backtick is not
C++ (C2001 newline-in-constant + C2015 too-many-chars + C2018 0x60
cascade, ~3 errors per site).  Corpus convention = the `vt_<Name>`
externs in e4_globals.hpp (`extern unsigned char vt_X[4]; // data: 0xADDR`).

The rewrite is address-authoritative:
  demangled ref -> vtable address (IDA names dump, keyword-normalized)
  -> in-tree vt_ symbol for that address (addr-join from e4_globals.hpp)
Unresolvable refs are kept verbatim (fail-loud census counts them).

Data files (both generated by .omo/evidence/optimization/x55/):
  x55_vtable_addr_map.json  {demangled "`Cls::`vftable''": addr-hex}
  x55_vt_addr_join.json     {addr-hex: vt_name}
"""
import json
import os
import re
from collections import Counter

_VTABLE_MAP_PATH = os.path.join('.omo', 'evidence', 'optimization', 'x55',
                                'x55_vtable_addr_map.json')
_VT_JOIN_PATH = os.path.join('.omo', 'evidence', 'optimization', 'x55',
                             'x55_vt_addr_join.json')
# Class text before ::`vftable' may carry deeply nested template args
# (VectorCursor<rc_ptr<X>,DynamicVectorClass<rc_ptr<X>>>), so a plain
# regex cannot express it.  Resolution walks BACKWARD from each
# "::`vftable'" tail with angle-bracket depth tracking: at depth 0 only
# name chars ([A-Za-z0-9_:,.*]) continue; spaces and expression chars
# ('&', '=', '(', ...) terminate.  The walk stops at the '&' of an
# address-of, which by construction yields the qualified class text.
_REF_TAIL = "::`vftable'"
_DEPTH0_NAME = re.compile(r'^[A-Za-z0-9_:,.*]$')

VFT_STATS = Counter()


def _vt_norm_ref(ref):
    """Demangled render ref (minus ::`vftable') -> canonical class text."""
    s = ref[:-len("::`vftable'")] if ref.endswith("::`vftable'") else ref
    s = re.sub(r'^const\s+', '', s.strip())
    s = re.sub(r'\b(class|struct|enum)\s+', '', s)
    return s


def _vt_load_maps():
    vmap = {}
    join = {}
    try:
        raw = json.load(open(_VTABLE_MAP_PATH, encoding='utf-8'))
    except OSError:
        raw = {}
    for k, v in raw.items():
        vmap[_vt_norm_ref(k)] = v.upper()
    try:
        join = json.load(open(_VT_JOIN_PATH, encoding='utf-8'))
    except OSError:
        join = {}
    return vmap, join


_VMAP, _VTJOIN = _vt_load_maps()


def _resolve_ref(ref):
    key = _vt_norm_ref(ref)
    addr = _VMAP.get(key)
    return _VTJOIN.get(addr) if addr else None


def fix_vftable_refs(body):
    """`Cls::`vftable'' -> `vt_X` (address-authoritative)."""
    if '`vftable' not in body:
        return body
    out = []
    idx = 0
    while True:
        j = body.find(_REF_TAIL, idx)
        if j < 0:
            out.append(body[idx:])
            break
        i = j - 1
        depth = 0
        while i >= 0:
            c = body[i]
            if c == '>':
                depth += 1
            elif c == '<':
                if depth == 0:
                    break
                depth -= 1
            elif depth == 0 and not _DEPTH0_NAME.match(c):
                break
            i -= 1
        start = i + 1
        ref = body[start:j]
        vt = None
        if ref and re.match(r'^[A-Za-z_]\w*', ref):
            vt = _resolve_ref(ref)
        if vt:
            out.append(body[idx:start])
            out.append(vt)
            VFT_STATS['vt-normalized'] += 1
        else:
            out.append(body[idx:j + len(_REF_TAIL)])
            VFT_STATS['vt-unresolved-kept'] += 1
        idx = j + len(_REF_TAIL)
    return ''.join(out)
