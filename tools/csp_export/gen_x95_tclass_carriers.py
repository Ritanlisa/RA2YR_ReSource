#!/usr/bin/env python3
"""X95 W2 - generate the missing e4 carriers for `TClassFactory_<T>`.

Authority (NO invented owners/layouts):
  * owner set   : anchors/csp_this_refined.json -- entries with status=resolved
                  whose owner is `TClassFactory_*` (X94 ctor-install evidence)
  * class size  : tools/class_layouts.json  (cross-checked against
                  .omo/evidence/optimization/x60/x60_til.json; must be equal)
  * field slots : the same two sources (offset existence) + the synthetic body
                  (`src/_gap2/gap2_global_defs.cpp`): every `this->NAME` must
                  map to an authority slot at the exact offset.
  * vport @0    : the ctor-install channel proved the vptr store at [this];
                  the body's `ptr_0` is that vport (X11 install comment).

Layout rule: emit `void* ptr_0` at 0 (vport), then the fields the body touches
at their exact offsets, then explicit `char __pad_*[N]` so that C++ sizeof ==
the authority size.  Header methods are preserved verbatim (existing carriers)
and added later by the X93 apply path (new carriers).

Outputs (all idempotent; dry-run unless --apply):
  src/e4/classes/<Owner>_e4.hpp        (63 created, Campaign rewritten)
  src/e4/TClassFactory_carriers_e4.cpp (single owner TU for X93 defs)
  src/e4/x95_carrier_sizeof_probe.cpp  (static_assert sizeof/offset proof)
  .omo/x95_carrier_manifest.json       (per-class evidence + sha of inputs)

Usage:
  python tools/csp_export/gen_x95_tclass_carriers.py            # dry run
  python tools/csp_export/gen_x95_tclass_carriers.py --apply
"""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
E4C = ROOT / "src" / "e4" / "classes"
SIDECAR = ROOT / "anchors" / "csp_this_refined.json"
LAYOUTS = ROOT / "tools" / "class_layouts.json"
TIL = ROOT / ".omo" / "evidence" / "optimization" / "x60" / "x60_til.json"
MEMBER_TYPES = ROOT / "anchors" / "member_types.json"
GAP2_DEFS = ROOT / "src" / "_gap2" / "gap2_global_defs.cpp"
GAP2_DECLS = ROOT / "src" / "_gap2" / "gap2_global_decls.hpp"
TU = ROOT / "src" / "e4" / "TClassFactory_carriers_e4.cpp"
PROBE = ROOT / "src" / "e4" / "x95_carrier_sizeof_probe.cpp"
MANIFEST = ROOT / ".omo" / "x95_carrier_manifest.json"
GEN_TAG = "// GENERATED by tools/csp_export/gen_x95_tclass_carriers.py -- DO NOT EDIT MANUALLY."

ADDR_RE = re.compile(r"^// 0x([0-9A-Fa-f]{6,8})\s*$")


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()[:16]


def load_defs():
    """address(int) -> (synthetic class, method, body text)"""
    text = GAP2_DEFS.read_text(encoding="latin-1")
    lines = text.split("\n")
    out = {}
    i = 0
    while i < len(lines):
        m = ADDR_RE.match(lines[i])
        if not m:
            i += 1
            continue
        addr = int(m.group(1), 16)
        start = i
        i += 1
        while i < len(lines) and not ADDR_RE.match(lines[i]):
            i += 1
        body = "\n".join(lines[start:i])
        dm = re.search(r"\b(Gap2Recv_[0-9A-Fa-f]+)::([A-Za-z_]\w*)\s*\(", body)
        if dm:
            out[addr] = (dm.group(1), dm.group(2), body)
    return out


def load_synthetic_decl_members():
    """synthetic class -> {member name: offset comment or None}"""
    text = GAP2_DECLS.read_text(encoding="latin-1")
    out = {}
    cur, start = None, 0
    for ln in text.split("\n"):
        m = re.match(r"\s*struct\s+(Gap2Recv_[0-9A-Fa-f]+)\s*\{", ln)
        if m:
            cur = m.group(1)
            out[cur] = {}
            continue
        if cur is None:
            continue
        if re.match(r"\s*\};", ln):
            cur = None
            continue
        mm = re.match(
            r"\s*(?:[A-Za-z_][\w:<>,\s\*]*?)\s+([A-Za-z_]\w*)\s*(?:\[[^\]]*\])?\s*;\s*(?://\s*(.*))?$",
            ln)
        if not mm or "(" in ln:
            continue
        name, com = mm.group(1), mm.group(2) or ""
        om = re.search(r"0x([0-9A-Fa-f]+)", com)
        out[cur].setdefault(name, int(om.group(1), 16) if om else None)
    return out


def field_offset(name, synth_members, size):
    """Exact offset for a body-touched name (authority-validated below).

    ptr_N convention: pointer field at word index N -> byte offset 4*N.
    The synthetic declaration is used only when it carries a real offset
    comment; its X10-supplied `ptr_0` at the wrong implicit slot is ignored.
    """
    m = re.match(r"^ptr_([0-9A-Fa-f]+)$", name)
    if m:
        off = int(m.group(1), 16) * 4
        if 0 <= off and off + 4 <= size:
            return off, "ptr_N convention (4*N)"
    o = synth_members.get(name)
    if o is not None and 0 <= o and o + 4 <= size:
        return o, "synthetic decl offset comment"
    return None, None


def render_header(owner, size, fields, methods, proof):
    lines = [
        GEN_TAG,
        "// Authority: tools/class_layouts.json size=0x%X == x60 til 0x%X; "
        "ctor-install vptr proof." % (size, size),
        "// Fields: %s; tail padded so C++ sizeof == authority size." % ", ".join(
            "%s@0x%X" % (n, o) for n, o in fields),
        "#pragma once",
        "",
        '#include "e4/classes/_fwd_e4.hpp"',
        "",
        "namespace gamemd {",
        "",
        "struct %s {" % owner,
    ]
    cur = 0
    for name, off in fields:
        if off > cur:
            lines.append("    char __pad_%X[%d];  // 0x%X" % (cur, off - cur, cur))
        lines.append("    void* %s;  // 0x%X" % (name, off))
        cur = off + 4
    if cur < size:
        lines.append("    char __pad_%X[%d];  // 0x%X" % (cur, size - cur, cur))
    for m in methods:
        lines.append("    " + m)
    lines += [
        "};",
        "",
        "} // namespace gamemd",
        "",
    ]
    return "\n".join(lines)


def existing_fields(owner):
    hp = E4C / ("%s_e4.hpp" % owner)
    if not hp.exists():
        return []
    out = []
    inside = False
    for ln in hp.read_text(encoding="utf-8", errors="replace").split("\n"):
        if re.match(r"\s*struct\s+%s\s*\{" % re.escape(owner), ln):
            inside = True
            continue
        if inside and re.match(r"\s*\};", ln):
            break
        m = (re.match(r"\s*void\*\s+(ptr_[0-9A-Fa-f]+)\s*;\s*//\s*0x([0-9A-Fa-f]+)",
                      ln) if inside else None)
        if m:
            if any(nm == m.group(1) for nm, _ in out):
                continue
            out.append((m.group(1), int(m.group(2), 16)))
    return out


def existing_methods(owner):
    hp = E4C / ("%s_e4.hpp" % owner)
    if not hp.exists():
        return []
    text = hp.read_text(encoding="utf-8", errors="replace")
    out = []
    inside = False
    for ln in text.split("\n"):
        if re.match(r"\s*struct\s+%s\s*\{" % re.escape(owner), ln):
            inside = True
            continue
        if inside and re.match(r"\s*\};", ln):
            break
        if inside and "(" in ln.split("//")[0] and ";" in ln.split("//")[0]:
            out.append(ln.strip())
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    args = ap.parse_args()

    side = json.load(open(SIDECAR, encoding="utf-8"))["entries"]
    layouts = json.load(open(LAYOUTS, encoding="utf-8"))
    til = json.load(open(TIL, encoding="utf-8"))
    mt = json.load(open(MEMBER_TYPES, encoding="utf-8"))
    defs = load_defs()
    synth = load_synthetic_decl_members()

    targets = []
    for a, v in sorted(side.items(), key=lambda kv: int(kv[0], 16)):
        owner = v.get("owner")
        if v.get("status") != "resolved" or not (owner or "").startswith(
                "TClassFactory"):
            continue
        addr = int(a, 16)
        # The synthetic body disappears once the relocation is applied; the
        # generator must stay idempotent afterwards (fields then come from the
        # generated carrier itself, still authority-validated below).
        if addr in defs:
            cls, method, body = defs[addr]
        else:
            cls, method, body = None, None, ""
        ctor = (v.get("evidence") or {}).get("ctor_install") or []
        assert v.get("rule") == "ctor-install" and ctor, \
            "%s: ctor-install evidence missing" % a
        lv, tv = layouts.get(owner), til.get(owner)
        assert lv and lv.get("size"), "%s: no class_layouts size" % owner
        size = int(lv["size"])
        assert tv and int(tv["size"]) == size, \
            "%s: class_layouts 0x%X != til 0x%X" % (
                owner, size, int((tv or {}).get("size") or 0))
        slots = {0: 4}
        for k, mm in (lv.get("offsets") or {}).items():
            try:
                slots[int(k)] = int((mm or {}).get("size") or 4)
            except (TypeError, ValueError):
                continue
        used = sorted(set(re.findall(r"this\s*->\s*([A-Za-z_]\w*)", body)))
        fields = []
        if not used:
            # post-apply idempotence: rebuild from the current carrier fields
            for nm, off in existing_fields(owner):
                used.append(nm)
                fields.append((off, nm, "existing carrier field (idempotent)"))
        if not used:
            raise AssertionError("%s: no body and no carrier fields" % owner)
        for nm in used:
            if fields and any(nm == f[1] for f in fields):
                continue
            off, why = field_offset(nm, synth.get(cls or "", {}), size)
            assert off is not None, "%s: no exact offset for %s" % (owner, nm)
            assert off in slots, \
                "%s: %s@0x%X absent from authority slots %s" % (
                    owner, nm, off, sorted(slots))
            assert slots[off] == 4, "%s: %s slot width != 4" % (owner, nm)
            fields.append((off, nm, why))
        fields.sort()
        # vport is always emitted (proven install), even if body never touches it
        if not fields or fields[0][0] != 0:
            fields.insert(0, (0, "ptr_0", "vport (ctor-install)"))
        assert fields[0] == (0, "ptr_0", fields[0][2])
        names = [n for _, n, _ in fields]
        assert len(names) == len(set(names)), "%s: duplicate field names" % owner
        targets.append({
            "address": a, "owner": owner, "method": method, "size": size,
            "slots": sorted(slots), "fields": [(n, o) for o, n, _ in fields],
            "field_evidence": {n: w for _, n, w in fields},
            "rule": v.get("rule"), "ctor_install": ctor,
            "member_types": sorted(k for k in mt if k.startswith(owner + "+")),
            "header": str((E4C / ("%s_e4.hpp" % owner)).relative_to(ROOT)).replace("\\", "/"),
        })

    assert len(targets) == 64, "expected 64 TClassFactory targets, got %d" % len(targets)

    # ---- render / write headers
    hdr_report = []
    for t in targets:
        owner = t["owner"]
        hp = E4C / ("%s_e4.hpp" % owner)
        methods = existing_methods(owner)
        text = render_header(owner, t["size"], t["fields"], methods, None)
        old = hp.read_text(encoding="utf-8", errors="replace") if hp.exists() else None
        changed = old != text
        if changed and args.apply:
            hp.write_text(text, encoding="utf-8", newline="\n")
        hdr_report.append({"owner": owner, "action": (
            "created" if old is None else ("rewritten" if changed else "unchanged")),
            "path": t["header"], "methods_preserved": len(methods)})
        t["header_action"] = hdr_report[-1]["action"]

    # ---- render / write owner TU
    tu_lines = [
        GEN_TAG,
        "// Single owner TU for the X95 TClassFactory carriers (X93 defs land here).",
        "#include <cstdint>",
    ]
    for t in targets:
        tu_lines.append('#include "%s"' % t["header"].replace("src/", ""))
    tu_lines.append("")
    tu_text = "\n".join(tu_lines)
    old_tu = TU.read_text(encoding="utf-8", errors="replace") if TU.exists() else None
    # X95: preserve the X93 definition block (appended by gen_gap2_defs.py).
    # Regenerating includes must never drop already-relocated bodies.
    if old_tu:
        b = "// --- x93 csp-relocation defs (BEGIN) ---"
        e = "// --- x93 csp-relocation defs (END) ---"
        if b in old_tu and e in old_tu:
            blk = old_tu[old_tu.index(b):old_tu.index(e) + len(e)]
            tu_text = tu_text.rstrip("\n") + "\n\n" + blk + "\n"
    if old_tu != tu_text and args.apply:
        TU.write_text(tu_text, encoding="utf-8", newline="\n")

    # ---- render / write sizeof probe
    p = [
        GEN_TAG,
        "// Compile-time proof: every carrier sizeof == authority size.",
        "// (Field offsets are proven by the contiguous/pad layout emitted above;",
        "// offsetof() is avoided because its MSVC expansion trips the AST gate.)",
        "#include <cstddef>",
    ]
    for t in targets:
        p.append('#include "%s"' % t["header"].replace("src/", ""))
    p += ["", "namespace {"]
    for t in targets:
        o = "gamemd::" + t["owner"]
        p.append("static_assert(sizeof(%s) == 0x%X, \"%s sizeof\");"
                 % (o, t["size"], t["owner"]))
    p += ["}  // namespace", ""]
    probe_text = "\n".join(p)
    old_p = PROBE.read_text(encoding="utf-8", errors="replace") if PROBE.exists() else None
    if old_p != probe_text and args.apply:
        PROBE.write_text(probe_text, encoding="utf-8", newline="\n")

    manifest = {
        "schema": "x95-carrier-manifest/v1",
        "generated_by": "tools/csp_export/gen_x95_tclass_carriers.py",
        "inputs_sha16": {
            "sidecar": sha(SIDECAR), "class_layouts": sha(LAYOUTS),
            "x60_til": sha(TIL), "member_types": sha(MEMBER_TYPES),
        },
        "targets": len(targets),
        "headers": hdr_report,
        "tu": str(TU.relative_to(ROOT)).replace("\\", "/"),
        "probe": str(PROBE.relative_to(ROOT)).replace("\\", "/"),
        "entries": targets,
    }
    if args.apply:
        MANIFEST.write_text(json.dumps(manifest, indent=1), encoding="utf-8")

    actions = {}
    for h in hdr_report:
        actions[h["action"]] = actions.get(h["action"], 0) + 1
    print("targets: %d  headers: %s" % (len(targets), actions))
    print("TU %s: %s" % (
        "unchanged" if old_tu == tu_text else "would write",
        TU.relative_to(ROOT).as_posix()))
    print("probe %s: %s" % (
        "unchanged" if old_p == probe_text else "would write",
        PROBE.relative_to(ROOT).as_posix()))
    print("APPLIED" if args.apply else "DRY RUN (use --apply)")
    if not args.apply:
        for h in hdr_report[:5]:
            print("  sample:", h)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
