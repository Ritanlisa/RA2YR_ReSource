#!/usr/bin/env python3
"""X119 -- export the IDA Hex-Rays lvar/defea channel as a durable artifact.

WHY
---
The CSP engine keys its `type_map.json` entries by SSA value:
`0x004BC750::edx_v0x4BD48A` (register value defined at 0x4BD48A) or
`0x00402C70::stack_-0xc` (frame slot).  The declarations emitted into the
source tree are Hex-Rays locals (`int v5`), and the only reliable bridge from
an emitted *name* to an SSA key is the Hex-Rays lvar itself:

  * register lvar -> `lvar.defea` -> the *containing instruction head* is the
    SSA version address (`get_item_head(defea)`, raw `defea` kept as a
    fallback probe -- the same two-probe order the historical t14 bridge
    used), plus `get_mreg_name(get_reg1(), 4)` for the register name.
  * stack lvar  -> `lvar.get_stkoff()` maps to the `stack_+0x..` /
    `stack_-0x..` family in type_map (same coordinate system the t14 bridge
    matched successfully).

That mapping (name -> defea/stkoff/reg) was never exported in bulk, so every
join attempt had to re-derive it from emitted `/*0xADDR*/` hints -- which do
not exist for ~7k declarations.  X119 dumps it once, into
`anchors/ida_lvars.json`, making the join reproducible offline forever after.

WHAT
----
For every function in the IDB (19,067), one record:

    "0x004BC750": {
      "lvars": {
        "v12": {"arg": 0, "fake": 0, "width": 8, "defea": 4966224,
                 "head": 4966224, "stkoff": null, "reg": "st6",
                 "type": "double"},
        ...},
      "this_type": "DSurface *"
    }

`defea`/`head` are null when Hex-Rays has no def site (BADADDR); `stkoff` is
null for non-stack lvars; `reg` is empty for non-register lvars.  `this_type`
is the type string of the argument lvar named `this`, when present.

MECHANICS
---------
IDA-side work runs through `ida-pro-mcp_py_exec_file` on a generated payload
(`.omo/x119_ida_payload.py`); each invocation processes as many 400-function
batches as fit into a 45 s budget (the MCP request deadline is ~60 s hard),
writing one atomic chunk per batch plus an atomic checkpoint -- so a killed
request loses nothing and the next call resumes (W4).  The host driver:

    python tools/csp_export/x119_export_lvars.py --gen-payload
    # then, repeatedly, in IDA MCP:  py_exec_file(.omo/x119_ida_payload.py)
    python tools/csp_export/x119_export_lvars.py --status
    python tools/csp_export/x119_export_lvars.py --merge
    python tools/csp_export/x119_export_lvars.py --sample 0x4BC750

IDEMPOTENCE
-----------
Chunks are keyed by the first address of their (deterministic, sorted) batch
and written with sort_keys; the merge reads every chunk, sorts, and writes the
artifact with fixed separators and NO volatile fields (no timestamps inside
the JSON).  Re-exporting the same IDB produces byte-identical chunks, hence a
byte-identical artifact.

The export is strictly read-only over the IDB: decompile + lvar inspection
only.  No idb_save is required and none is performed.
"""
import argparse
import hashlib
import json
import os
import sys
import time
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ART = ROOT / "anchors" / "ida_lvars.json"
PAYLOAD = ROOT / ".omo" / "x119_ida_payload.py"
CHUNKS = ROOT / ".omo" / "x119_chunks"
CKPT = ROOT / ".omo" / "x119_checkpoint.json"
TYPE_MAP = ROOT / "type_map.json"

# time budget per py_exec_file invocation, seconds (MCP deadline is ~60 s)
BUDGET_S = 35.0
BATCH = 250

PAYLOAD_TEMPLATE = r'''# X119 IDA-side payload -- generated by tools/csp_export/x119_export_lvars.py
# Run inside IDA via ida-pro-mcp py_exec_file.  Read-only over the IDB.
# Resume-safe: 400-function batches, atomic chunk + atomic checkpoint,
# 45 s budget per invocation (MCP request deadline is ~60 s).
import json
import os
import time

import idaapi
import idautils
import idc
import ida_hexrays

ROOT = __ROOT__
CKPT = __CKPT__
CHUNKS = __CHUNKS__
BUDGET_S = __BUDGET__
BATCH = __BATCH__


def loadj(path, default):
    try:
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return default


def savej(obj, path):
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(obj, f, separators=(",", ":"), sort_keys=True)
    os.replace(tmp, path)


def fmt_type(t):
    try:
        d = t().dstr() if callable(t) else t.dstr()
        return d or ""
    except Exception:
        return ""


def export_func(ea):
    try:
        cf = ida_hexrays.decompile(ea)
    except Exception:
        return {"lvars": {}, "fail": "decompile"}
    if cf is None:
        return {"lvars": {}, "fail": "decompile"}
    out = {}
    this_type = None
    lvs = cf.get_lvars()
    for i in range(len(lvs)):
        lv = lvs[i]
        rec = {}
        try:
            rec["arg"] = 1 if lv.is_arg_var else 0
        except Exception:
            rec["arg"] = 0
        try:
            rec["fake"] = 1 if lv.is_fake_var else 0
        except Exception:
            rec["fake"] = 0
        try:
            rec["width"] = int(lv.width)
        except Exception:
            rec["width"] = 0
        d = lv.defea
        if d is not None and d != idaapi.BADADDR and d < 0xFFFFFFFF:
            rec["defea"] = int(d)
            try:
                rec["head"] = int(idc.get_item_head(d))
            except Exception:
                rec["head"] = int(d)
        else:
            rec["defea"] = None
            rec["head"] = None
        try:
            so = lv.get_stkoff()
            rec["stkoff"] = int(so) if so not in (None, -1) else None
        except Exception:
            rec["stkoff"] = None
        reg = ""
        try:
            if lv.is_reg_var():
                reg = ida_hexrays.get_mreg_name(lv.get_reg1(), 4).split("^")[0] or ""
        except Exception:
            reg = ""
        rec["reg"] = reg
        rec["type"] = fmt_type(lv.type)
        if rec["arg"] and lv.name == "this" and rec["type"]:
            this_type = rec["type"]
        out[lv.name] = rec
    return {"lvars": out, "this_type": this_type}


def main():
    if not ida_hexrays.init_hexrays_plugin():
        print("X119 FATAL: hexrays unavailable")
        return
    funcs = sorted(set(int(f) for f in idautils.Functions()))
    ck = loadj(CKPT, {"done": []})
    done = set(ck.get("done", []))
    pending = [f for f in funcs if f not in done]
    print("X119 start total=%d pending=%d" % (len(funcs), len(pending)))
    if not pending:
        print("X119 EXPORT COMPLETE")
        return
    try:
        os.makedirs(CHUNKS, exist_ok=True)
    except OSError:
        pass
    t0 = time.time()
    while pending and (time.time() - t0) < BUDGET_S:
        batch, pending = pending[:BATCH], pending[BATCH:]
        chunk = {}
        for ea in batch:
            chunk["0x%08x" % ea] = export_func(ea)
            done.add(ea)
        cname = "chunk_%08x.json" % batch[0]
        savej(chunk, os.path.join(CHUNKS, cname))
        ck["done"] = sorted(done)
        savej(ck, CKPT)
    print("X119 progress total=%d done=%d remaining=%d elapsed=%.1f"
          % (len(funcs), len(done), len(pending), time.time() - t0))
    if not pending:
        print("X119 EXPORT COMPLETE")


main()
'''


def gen_payload():
    PAYLOAD.parent.mkdir(parents=True, exist_ok=True)
    body = (PAYLOAD_TEMPLATE
            .replace("__ROOT__", repr(str(ROOT)))
            .replace("__CKPT__", repr(str(CKPT)))
            .replace("__CHUNKS__", repr(str(CHUNKS)))
            .replace("__BUDGET__", repr(BUDGET_S))
            .replace("__BATCH__", repr(BATCH)))
    PAYLOAD.write_text(body, encoding="utf-8")
    print("payload written:", PAYLOAD)


def status():
    ck = {}
    if CKPT.exists():
        ck = json.load(open(CKPT, encoding="utf-8"))
    done = ck.get("done", [])
    chunks = sorted(CHUNKS.glob("chunk_*.json")) if CHUNKS.exists() else []
    print("done: %d functions, %d chunks" % (len(done), len(chunks)))
    if CKPT.exists():
        print("checkpoint:", CKPT)


def _iter_chunks():
    if not CHUNKS.exists():
        return
    for cp in sorted(CHUNKS.glob("chunk_*.json")):
        part = json.load(open(cp, encoding="utf-8"))
        for fa, rec in part.items():
            yield fa, rec


def merge():
    """Fold all chunks into anchors/ida_lvars.json (deterministic, atomic)."""
    functions = {}
    for fa, rec in _iter_chunks():
        functions[fa] = rec
    cov = Counter()
    lvar_total = 0
    fails = 0
    for fa, rec in functions.items():
        if rec.get("fail"):
            fails += 1
            continue
        if rec.get("this_type"):
            cov["this_type_present"] += 1
        for name, lv in rec["lvars"].items():
            lvar_total += 1
            if lv.get("arg"):
                cov["lvars_arg"] += 1
            if lv.get("fake"):
                cov["lvars_fake"] += 1
            if lv.get("defea") is not None:
                cov["lvars_defea"] += 1
            if lv.get("stkoff") is not None:
                cov["lvars_stack"] += 1
            if lv.get("reg"):
                cov["lvars_reg"] += 1
            if lv.get("type"):
                cov["lvars_typed"] += 1
    manifest = {
        "functions_total": len(functions),
        "functions_decompile_fail": fails,
        "lvars_total": lvar_total,
        "lvars_arg": cov["lvars_arg"],
        "lvars_fake": cov["lvars_fake"],
        "lvars_defea": cov["lvars_defea"],
        "lvars_stack": cov["lvars_stack"],
        "lvars_reg": cov["lvars_reg"],
        "lvars_typed": cov["lvars_typed"],
        "this_type_present": cov["this_type_present"],
    }
    artifact = {
        "_meta": {
            "tool": "tools/csp_export/x119_export_lvars.py",
            "format": 1,
            "note": ("Hex-Rays lvar dump: name -> defea/head/stkoff/reg/type; "
                     "this_type from the argument lvar named 'this'. "
                     "head = idc.get_item_head(defea) is the SSA version "
                     "address; defea is kept as fallback probe."),
        },
        "manifest": manifest,
        "functions": dict(sorted(functions.items())),
    }
    blob = json.dumps(artifact, separators=(",", ":"), sort_keys=True)
    ART.parent.mkdir(parents=True, exist_ok=True)
    tmp = str(ART) + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(blob)
    os.replace(tmp, str(ART))
    print("artifact:", ART)
    print("sha256  :", hashlib.sha256(blob.encode("utf-8")).hexdigest())
    print("manifest:", json.dumps(manifest, indent=1))


def sample(addr_str):
    """Show one function's lvars next to the type_map SSA keys they resolve to."""
    addr = int(addr_str, 16)
    fa = "0x%08x" % addr
    if not ART.exists():
        sys.exit("artifact missing; run --merge first")
    art = json.load(open(ART, encoding="utf-8"))
    rec = art["functions"].get(fa)
    if rec is None:
        sys.exit("function %s not in artifact" % fa)
    tm = json.load(open(TYPE_MAP, encoding="utf-8"))["type_map"]
    fk = "0x%08x" % addr
    keys = {}
    for k, v in tm.items():
        if k.lower().startswith(fk + "::"):
            keys[k.split("::", 1)[1].lower()] = v
    print("function %s: %d lvars, %d type_map keys, this=%s"
          % (fa, len(rec["lvars"]), len(keys), rec.get("this_type")))
    hits = 0
    for name in sorted(rec["lvars"]):
        lv = rec["lvars"][name]
        cands = []
        if lv.get("stkoff") is not None:
            so = lv["stkoff"]
            cands.append(("stack_+0x%x" % so) if so >= 0
                         else ("stack_-0x%x" % -so))
        if lv.get("reg"):
            for base in (lv.get("head"), lv.get("defea")):
                if base is not None:
                    cands.append("%s_v0x%X" % (lv["reg"], base))
        found = None
        for c in cands:
            ent = keys.get(c.lower())
            if ent is not None:
                found = (c, ent)
                break
        tag = ("-> " + found[0] + " : " + str(found[1].get("type"))
               + " [" + str(found[1].get("confidence")) + "]") if found \
            else "(no key)"
        if found:
            hits += 1
        print("  %-8s defea=%s head=%s stkoff=%s reg=%-4s type=%-16s %s"
              % (name, lv["defea"], lv["head"], lv["stkoff"], lv["reg"],
                 (lv["type"] or "")[:16], tag))
    print("sample key hits: %d/%d lvars" % (hits, len(rec["lvars"])))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--gen-payload", action="store_true")
    ap.add_argument("--status", action="store_true")
    ap.add_argument("--merge", action="store_true")
    ap.add_argument("--sample", default=None)
    args = ap.parse_args()
    if args.gen_payload:
        gen_payload()
    if args.status:
        status()
    if args.merge:
        merge()
    if args.sample:
        sample(args.sample)


if __name__ == "__main__":
    main()
