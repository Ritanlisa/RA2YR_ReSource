# ---------------- signature parsing (identical to s7) ----------------
def split_top(s):
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch in '(<':
            depth += 1
        elif ch in ')>':
            depth -= 1
        if depth == 0 and ch == ',':
            out.append(cur); cur = ''
        else:
            cur += ch
    if cur.strip():
        out.append(cur)
    return [x.strip() for x in out if x.strip()]

TYPEWORDS = {'void', 'int', 'char', 'short', 'long', 'unsigned', 'signed',
             'float', 'double', 'bool', 'wchar_t', 'size_t', 'const', 'volatile'}

def parse_sig(blk):
    i = blk.find('{')
    if i < 0:
        return None
    head = blk[:i]
    lines = [l for l in head.split('\n') if l.strip()
             and not l.strip().startswith('//') and not l.strip().startswith('#include')]
    sig = ' '.join(l.strip() for l in lines).strip()
    m = re.match(r'^(.*)\((.*)\)\s*$', sig)
    if not m:
        return None
    pre, ps = m.group(1).strip(), m.group(2).strip()
    star = ''
    if pre.endswith('*'):
        pre = pre[:-1].rstrip(); star = '*'
    mm = re.search(r'([A-Za-z_~]\w*(?:::[A-Za-z_~]\w*)*)\s*$', pre)
    if not mm:
        return None
    qual = mm.group(1)
    ret = (pre[:mm.start()] + ' ' + star).strip()
    cc = None
    cm = re.search(r'__(thiscall|stdcall|cdecl|fastcall)\b', ret)
    if cm:
        cc = cm.group(1)
        ret = (ret[:cm.start()] + ret[cm.end():]).strip()
    params = []
    if ps and ps != 'void':
        for p in split_top(ps):
            p = re.sub(r'\s*=\s*[^,]+$', '', p).strip()
            if not p:
                continue
            toks = p.split()
            if len(toks) == 1:
                params.append((p, None)); continue
            last = toks[-1]
            if re.fullmatch(r'[A-Za-z_]\w*', last) and last not in TYPEWORDS:
                params.append((' '.join(toks[:-1]).strip(), last))
            else:
                params.append((p, None))
    return ret, cc, qual, params

MEMFAM = {
    'char': ['char', 'unsigned char'], 'unsigned char': ['char', 'unsigned char'],
    'signed char': ['char', 'unsigned char'],
    'short': ['short', 'unsigned short'], 'unsigned short': ['short', 'unsigned short'],
    'wchar_t': ['short', 'unsigned short'],
    'int': ['int', 'unsigned int'], 'unsigned int': ['int', 'unsigned int'],
    'long': ['int', 'unsigned int'], 'unsigned long': ['int', 'unsigned int'],
    'float': ['float'], 'double': ['double'], 'bool': ['bool'],
    '__int64': [], 'unsigned __int64': [],
}

hpp_cache = {}

def hpp_members(pdir, unit, blk):
    key = (pdir, unit)
    if key in hpp_cache:
        return hpp_cache[key]
    inc = None
    for m in INC.finditer(blk):
        if m.group(1).endswith('.hpp'):
            inc = m.group(1); break
    paths = []
    if inc:
        paths.append(os.path.join(pdir, 'include', inc))
    incdir = os.path.join(pdir, 'include')
    if os.path.isdir(incdir):
        for f in glob.glob(os.path.join(incdir, '*.hpp')):
            if os.path.splitext(os.path.basename(f))[0] == unit:
                paths.append(f)
    res = {}
    for c in paths:
        if not os.path.exists(c):
            continue
        union_off = None
        union_depth = 0
        for l in open(c, encoding='utf-8', errors='replace'):
            mh = UNIONHDR.match(l)
            if mh:
                union_off = int(mh.group(1), 16)
                union_depth = 1
                continue
            if union_depth:
                if '};' in l or re.match(r'^\s*\}\s*;', l):
                    union_depth = 0
                    union_off = None
                    continue
                m = re.match(r'^\s*(.+?)\s+([A-Za-z_]\w*)\s*(\[[^\]]*\])?\s*;', l)
                if m and union_off is not None:
                    res.setdefault(m.group(2), (m.group(1).strip(), m.group(3), union_off))
                continue
            m = MEMDECL.match(l)
            if m:
                res.setdefault(m.group(2), (m.group(1).strip(), m.group(3), int(m.group(4), 16)))
        if res:
            break
    hpp_cache[key] = res
    return res

