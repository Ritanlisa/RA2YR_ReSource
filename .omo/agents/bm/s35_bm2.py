        if not decl:
            dropped['member-nodecl'] += 1; continue
        ty, arr, off = decl
        if off == 0 or nm.startswith('vfptr'):
            dropped['member-vfptr'] += 1; continue
        if arr and not re.fullmatch(r'\[\s*1\s*\]', arr):
            dropped['member-array'] += 1; continue
        fam = MEMFAM.get(norm_ty(ty))
        if fam is None:
            dropped['member-type-external'] += 1; continue
        if not fam:
            dropped['member-type-empty'] += 1; continue
        ok = [t for t in fam if t.lower() in vocab]
        if not ok:
            dropped['member-type-vocab'] += 1; continue
        rec = dict(base)
        rec.update({'ent': 'M:%X:this:0x%X' % (fn, off), 'types': ok, 'via': 'bm-member',
                    'tier': 'strict', 'member': nm, 'decl_ty': ty, 'proof': 'width-pinned'})
        recs.append(rec); stats['member'] += 1

