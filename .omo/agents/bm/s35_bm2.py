# ---------------- G6/G7: dedupe + conflict against EVERY family (incl. round-1 BM) ----------------
known = collections.defaultdict(set)
def walk(o):
    if isinstance(o, dict):
        e = o.get('ent')
        if isinstance(e, str):
            ts = o.get('types') or o.get('classes')
            if isinstance(ts, list) and ts:
                for t in ts:
                    if isinstance(t, str):
                        known[e].add(norm_ty(t).lower())
        for v in o.values():
            walk(v)
    elif isinstance(o, list):
        for v in o:
            walk(v)

