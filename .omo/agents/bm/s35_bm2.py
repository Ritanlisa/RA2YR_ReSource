    # ---------- bm-sig ----------
    if size < SIG_MIN_SIZE:
        dropped['sig-small'] += 1
    else:
        body_wo_sig = blk.split('{', 1)[-1]
        returns_this = bool(re.search(r'return[^;]*\bthis\b', body_wo_sig))
        rt = norm_ty(ret)
        if rt and rt != 'void':
            if returns_this:
                dropped['ret-returns-this'] += 1
            elif rt.lower() in BM_SIG_EXCLUDE:
                dropped['ret-int-family'] += 1
            elif rt.lower() in vocab:
                rec = dict(base)
                rec.update({'ent': 'RET:%X' % fn, 'types': [rt], 'via': 'bm-sig', 'tier': 'strict',
                            'cc': cc, 'proof': 'codegen-consistent'})
                recs.append(rec); stats['ret'] += 1
            else:
                dropped['ret-vocab'] += 1
        for k, (pt, pn) in enumerate(params):
            npt = norm_ty(pt)
            if not npt or npt == 'void':
                dropped['param-void'] += 1; continue
            if npt.lower() in BM_SIG_EXCLUDE:
                dropped['param-int-family'] += 1; continue
            if npt.lower() not in vocab:
                dropped['param-vocab'] += 1; continue
            if not (pn and re.search(r'\b' + re.escape(pn) + r'\b', body_wo_sig)):
                dropped['param-unused'] += 1; continue
            rec = dict(base)
            rec.update({'ent': 'P:%X:%d' % (fn, k), 'types': [npt], 'via': 'bm-sig', 'tier': 'strict',
                        'cc': cc, 'param': pn, 'proof': 'codegen-consistent'})
            recs.append(rec); stats['param'] += 1

    # ---------- bm-member ----------
    if not cls:
        continue
    body = blk.split('{', 1)[-1]
    names = set(re.findall(r'this->([A-Za-z_]\w*)', body))
    if not names:
        continue
    memdeck = hpp_members(pdir, r.get('unit') or '', blk)
    if not memdeck:
        dropped['member-hpp-miss'] += 1
        continue
