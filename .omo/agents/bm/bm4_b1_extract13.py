print('picked cpp defs:', len(picked))

cdb = json.load(open('anchors/class_db.json', encoding='utf-8'))['classes']
uni = json.load(open('anchors/universe_binary_classes.json', encoding='utf-8'))
tu = json.load(open('anchors/type_universe.json', encoding='utf-8'))
vocab_cls = set(cdb) | set(uni.get('restore_from_dead') or []) | set(uni.get('add_new') or [])


def norm_ty(t):
    t = str(t).strip()
    t = re.sub(r'\s+', ' ', t)
    t = t.replace(' *', '*').replace('* ', '*')
    if t == 'const char*':
        return 'char*'
    return t


vocab = {norm_ty(x).lower() for x in vocab_cls} | {norm_ty(x).lower() for x in (tu.get('types') or [])}
_pv = json.load(open('.omo/agents/bm/proven_classes.json', encoding='utf-8'))
proven_cls = {x.lower() for x in _pv['proven']}


def split_top(s):
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch in '(<':
            depth += 1
        elif ch in ')>':
            depth -= 1
        if depth == 0 and ch == ',':
            out.append(cur); cur = ''
        else:
            cur += ch
    if cur.strip():
        out.append(cur)
    return [x.strip() for x in out if x.strip()]


TYPEWORDS = {'void', 'int', 'char', 'short', 'long', 'unsigned', 'signed',
             'float', 'double', 'bool', 'wchar_t', 'size_t', 'const', 'volatile'}


def parse_sig(blk):
    i = blk.find('{')
    if i < 0:
        return None
    head = blk[:i]
    lines = [l for l in head.split('\n') if l.strip()
             and not l.strip().startswith('//') and not l.strip().startswith('#include')]
    sig = ' '.join(l.strip() for l in lines).strip()
    m = re.match(r'^(.*)\((.*)\)\s*$', sig)
    if not m:
        return None
    pre, ps = m.group(1).strip(), m.group(2).strip()
    star = ''
    if pre.endswith('*'):
        pre = pre[:-1].rstrip(); star = '*'
    mm = re.search(r'([A-Za-z_~]\w*(?:::[A-Za-z_~]\w*)*)\s*$', pre)
    if not mm:
        return None
    qual = mm.group(1)
    ret = (pre[:mm.start()] + ' ' + star).strip()
    cc = None
    cm = re.search(r'__(thiscall|stdcall|cdecl|fastcall)\b', ret)
    if cm:
        cc = cm.group(1)
        ret = (ret[:cm.start()] + ret[cm.end():]).strip()
    params = []
    if ps and ps != 'void':
        for p in split_top(ps):
            p = re.sub(r'\s*=\s*[^,]+$', '', p).strip()
            if not p:
                continue
            toks = p.split()
            if len(toks) == 1:
                params.append((p, None)); continue
            last = toks[-1]
            if re.fullmatch(r'[A-Za-z_]\w*', last) and last not in TYPEWORDS:
                params.append((' '.join(toks[:-1]).strip(), last))
            else:
                params.append((p, None))
    return ret, cc, qual, params


MEMFAM = {
    'char': ['char', 'unsigned char'], 'unsigned char': ['char', 'unsigned char'],
    'signed char': ['char', 'unsigned char'],
    'short': ['short', 'unsigned short'], 'unsigned short': ['short', 'unsigned short'],
    'wchar_t': ['short', 'unsigned short'],
    'int': ['int', 'unsigned int'], 'unsigned int': ['int', 'unsigned int'],
    'long': ['int', 'unsigned int'], 'unsigned long': ['int', 'unsigned int'],
    'float': ['float'], 'double': ['double'], 'bool': ['bool'],
    '__int64': [], 'unsigned __int64': [],
}
SIG_MIN_SIZE = 5
BM_SIG_EXCLUDE = {'int', 'unsigned int', 'long', 'unsigned long', 'DWORD'}
hpp_cache = {}


def hpp_members(pdir, unit, blk):
    key = (pdir, unit)
    if key in hpp_cache:
        return hpp_cache[key]
    inc = None
    for m in INC.finditer(blk):
        if m.group(1).endswith('.hpp'):
            inc = m.group(1); break
    paths = []
    if inc:
        paths.append(os.path.join(pdir, 'include', inc))
    incdir = os.path.join(pdir, 'include')
    if os.path.isdir(incdir):
        for f in glob.glob(os.path.join(incdir, '*.hpp')):
            if os.path.splitext(os.path.basename(f))[0] == unit:
                paths.append(f)
    if inc:
        beside = os.path.join(pdir, inc)
        if beside not in paths:
            paths.append(beside)
    res = {}
    for c in paths:
        if not os.path.exists(c):
            continue
        for l in open(c, encoding='utf-8', errors='replace'):
            m = MEMDECL.match(l)
            if m:
                res.setdefault(m.group(2), (m.group(1).strip(), m.group(3), int(m.group(4), 16)))
        if res:
            break
    hpp_cache[key] = res
    return res


# NOTE: we do NOT re-apply G6/G7 here: the 13 rows are exactly the rows the
# original run emitted for these fns (they passed G6 dedupe + G7 conflict THEN).
# We reconstruct them verbatim; G6 against the current file drops none of them
# (they were removed by repair, so no ent collisions exist).
recs = []
for a, (pdir, r, up, blk) in sorted(picked.items()):
    fn = int(a, 16)
    size = r.get('orig_size') or 0
    ps = parse_sig(blk)
    if not ps:
        continue
    ret, cc, qual, params = ps
    cls = qual.split('::')[0] if '::' in qual else None
    base = {'fn': '0x%08X' % fn, 'size': size, 'src': 'bm3'}
    if cls:
        if cls.lower() in vocab and str(r.get('cls_src') or '') != 'name_prefix' \
                and cls.lower() in proven_cls:
            recs.append(dict(base, ent='T:%X' % fn, types=[cls], via='bm-owner',
                             tier='strict', cls_src=r.get('cls_src'), proof='ledger-attribution'))
    if size >= SIG_MIN_SIZE:
        body_wo_sig = blk.split('{', 1)[-1]
        returns_this = bool(re.search(r'return[^;]*\bthis\b', body_wo_sig))
        rt = norm_ty(ret)
        if rt and rt != 'void' and not returns_this and rt.lower() not in BM_SIG_EXCLUDE \
                and rt.lower() in vocab:
            recs.append(dict(base, ent='RET:%X' % fn, types=[rt], via='bm-sig', tier='strict',
                             cc=cc, proof='codegen-consistent'))
        for k, (pt, pn) in enumerate(params):
            npt = norm_ty(pt)
            if not npt or npt == 'void' or npt.lower() in BM_SIG_EXCLUDE:
                continue
            if npt.lower() not in vocab:
                continue
            if not (pn and re.search(r'\b' + re.escape(pn) + r'\b', body_wo_sig)):
                continue
            recs.append(dict(base, ent='P:%X:%d' % (fn, k), types=[npt], via='bm-sig',
                             tier='strict', cc=cc, param=pn, proof='codegen-consistent'))
    if cls:
        body = blk.split('{', 1)[-1]
        names_ = set(re.findall(r'this->([A-Za-z_]\w*)', body))
        memdeck = hpp_members(pdir, r.get('unit') or '', blk)
        for nm in sorted(names_):
            decl = memdeck.get(nm)
            if not decl:
                continue
            ty, arr, off = decl
            if off == 0 or nm.startswith('vfptr'):
                continue
            if arr and not re.fullmatch(r'\[\s*1\s*\]', arr):
                continue
            fam = MEMFAM.get(norm_ty(ty))
            if fam is None or not fam:
                continue
            ok = [t for t in fam if t.lower() in vocab]
            if not ok:
                continue
            recs.append(dict(base, ent='M:%X:this:0x%X' % (fn, off), types=ok,
                             via='bm-member', tier='strict', member=nm, decl_ty=ty,
                             proof='width-pinned'))

print('reconstructed rows for the 6 fns:', len(recs))
for rec in recs:
    print('   ', rec['ent'], rec['types'], rec.get('via'), rec.get('cls_src') or rec.get('member') or '')

# cross-check against repair_log.dropped_ents
expect = set(doc['meta']['round3']['repair_log']['dropped_ents'])
got = {r['ent'] for r in recs}
print('repair_log expects:', len(expect), '| reconstructed:', len(got))
print('missing:', sorted(expect - got))
print('extra  :', sorted(got - expect))

json.dump(recs, open('.omo/agents/bm/bm4_repro_rows.json', 'w'), indent=1)
print('written .omo/agents/bm/bm4_repro_rows.json')
