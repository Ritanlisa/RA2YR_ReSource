INC = re.compile(r'#include\s+"([^"]+)"')
MEMDECL = re.compile(r'^\s*(.+?)\s+([A-Za-z_]\w*)\s*(\[[^\]]*\])?\s*;\s*(?:/\*.*?\*/\s*)?//\s*@?0x([0-9A-Fa-f]+)')


def norm_addr(a):
    return ('0x%08x' % int(a, 16)).lower()


doc = json.load(open('anchors/byte_match_types.json', encoding='utf-8'))
EV = doc['evidence']
