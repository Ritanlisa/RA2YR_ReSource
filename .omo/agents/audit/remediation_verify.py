#!/usr/bin/env python3
"""remediation_verify.py -- before/after verification for the audit fixes.

A. 43 rule-violation functions: pre-fix emission (rem_before43) vs post-fix
   emission (rem_clean44) -- checker must be all-red before, all-green after.
B. 0x602AE0 this-as-id: archived body (18 R7) vs fixed body (0 R7), 161B equal.
C. identity drift: all 100 class-drift cases re-run -- ledger name == emitted.
D. regression sample: 40 OK functions re-run -- MATCH + 0 violations.
E. 0x48ACE0: sentinel class "Return" -> honest free __stdcall function.
F. full OK artifact scan: how many of the 424 archived MATCH bodies trip the
   new R7 semantic rule (expect exactly the 161B case).
"""
import glob
import json
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "tools", "decomp_sys"))
import checker  # noqa: E402

AUDIT = os.path.join(ROOT, ".omo", "agents", "audit")


def iter_cpp_blocks(cpp_path):
    txt = open(cpp_path, encoding="utf-8", errors="replace").read()
    for blk in txt.split("// GENERATED by tools/decomp_sys/decompile.py"):
        m = re.search(r"fn 0x([0-9A-F]+) \(([^)]*)\)", blk)
        if not m:
            continue
        i, j = blk.find("{"), blk.rfind("}")
        if i < 0 or j <= i:
            continue
        yield ("0x" + m.group(1).lower(), m.group(2), blk[i + 1:j])


def check_tree(pattern):
    out = {}
    for cpp in glob.glob(pattern):
        for addr, sig, body in iter_cpp_blocks(cpp):
            cls = sig.split("::")[0] if "::" in sig else sig
            rep = checker.check_function(cls, body, set(), None)
            out[addr] = {
                "sig": sig,
                "violations": [{"rule": v["rule"], "pattern": v["pattern"],
                                "detail": v["detail"]} for v in rep.violations],
            }
    return out


def part_reports(pattern):
    res = {}
    for p in glob.glob(pattern):
        d = json.load(open(p, encoding="utf-8"))
        for r in d.get("results", []):
            res[r["addr"]] = r
    return res


def main():
    addrs = [a.strip() for a in
             open(os.path.join(AUDIT, "remediation_43.txt"),
                  encoding="utf-8").read().split() if a.strip()]

    print("== A. 43 violation functions ==")
    before = check_tree(os.path.join(AUDIT, "rem_before43", "part_*", "*.cpp"))
    after = check_tree(os.path.join(AUDIT, "rem_clean44", "part_*", "*.cpp"))
    after_rep = part_reports(os.path.join(AUDIT, "rem_clean44", "part_*",
                                          "part_report.json"))
    a_rows = []
    for a in addrs:
        b = before.get(a, {})
        n = after.get(a, {})
        r = after_rep.get(a, {})
        a_rows.append({
            "addr": a, "sig": b.get("sig") or n.get("sig"),
            "before_violations": len(b.get("violations") or []),
            "before_rules": sorted({v["rule"] + ":" + v["pattern"]
                                    for v in (b.get("violations") or [])}),
            "after_violations": len(n.get("violations") or []),
            "after_verdict": r.get("verdict"),
            "after_clean": r.get("clean"),
        })
    red = sum(1 for r in a_rows if r["before_violations"])
    green = sum(1 for r in a_rows if r["after_violations"] == 0
                and r["after_verdict"] == "MATCH")
    print("  before: %d/%d red (violations present)" % (red, len(a_rows)))
    print("  after : %d/%d green (0 violations + MATCH)" % (green, len(a_rows)))

    print("== B. 0x602AE0 this-as-id ==")
    old_tree = check_tree(os.path.join(
        ROOT, ".omo", "decomp_batch", "r5_regression_final", "p09",
        "part_00", "Dialog.cpp"))
    old = old_tree.get("0x602ae0", {})
    new = after.get("0x602ae0", {})
    old_r7 = [v for v in old.get("violations") or [] if v["rule"] == "R7"]
    new_r7 = [v for v in new.get("violations") or [] if v["rule"] == "R7"]
    orig = json.load(open(os.path.join(
        ROOT, ".omo", "decomp_batch", "r5_regression_final", "p09",
        "part_00", "orig_602AE0.json"), encoding="utf-8"))
    new_rows = glob.glob(os.path.join(AUDIT, "rem_clean44", "part_*",
                                      "ours_602AE0.json"))
    ours = json.load(open(new_rows[0], encoding="utf-8")) if new_rows else {}
    b_bytes = orig["bytes_hex"].lower()
    o_bytes = (ours.get("bytes_hex") or "").lower()
    print("  old R7 violations: %d" % len(old_r7))
    print("  new R7 violations: %d" % len(new_r7))
    print("  bytes equal: %s (%dB vs %dB)" % (
        b_bytes == o_bytes, len(b_bytes) // 2, len(o_bytes) // 2))

    print("== C. identity drift (all 100) ==")
    stat = json.load(open(os.path.join(ROOT, ".omo", "codegen_match",
                                       "status.json"), encoding="utf-8"))
    id_rep = part_reports(os.path.join(AUDIT, "drift_clean100", "part_*",
                                       "part_report.json"))
    c_rows = []
    for a, r in sorted(id_rep.items()):
        e = stat.get(a, {})
        c_rows.append({
            "addr": a, "orig_name": e.get("orig_name"),
            "ledger_name": e.get("name"), "emitted": r.get("emitted"),
            "cls_src": e.get("cls_src"),
            "name_equal": e.get("name") == r.get("emitted"),
            "verdict": r.get("verdict"), "clean": r.get("clean"),
        })
    drift = sum(1 for r in c_rows if not r["name_equal"])
    sentinel = sum(1 for r in c_rows
                   if (r["emitted"] or "").split("::")[0] in ("unknown",
                                                              "Return"))
    print("  sample: %d, ledger!=emitted: %d, sentinel units: %d"
          % (len(c_rows), drift, sentinel))

    print("== D. regression sample ==")
    reg = part_reports(os.path.join(AUDIT, "regress_clean40", "part_*",
                                    "part_report.json"))
    reg_match = sum(1 for r in reg.values() if r.get("verdict") == "MATCH")
    reg_viol = sum(1 for r in reg.values()
                   if (r.get("rule_violations") or 0) > 0)
    print("  %d/%d MATCH, rule violations: %d"
          % (reg_match, len(reg), reg_viol))

    print("== E. 0x48ACE0 sentinel free emission ==")
    free_txt = ""
    for cpp in glob.glob(os.path.join(AUDIT, "drift_clean100", "part_*",
                                      "*Return*.cpp")):
        txt = open(cpp, encoding="utf-8", errors="replace").read()
        if "0x48ACE0" in txt:
            free_txt = txt
            break
    free_sig = None
    m = re.search(r"^(int __stdcall HRESULT_Fail\([^)]*\))$", free_txt,
                  re.M)
    if m:
        free_sig = m.group(1)
    print("  emitted: %s" % (free_sig or "(not found)"))
    print("  0x48ace0 verdict: %s" % (id_rep.get("0x48ace0", {})
                                      .get("verdict")))

    print("== F. full OK artifact R7 scan ==")
    idx = json.load(open(os.path.join(ROOT, ".omo", "audit", "index.json"),
                         encoding="utf-8"))
    best = idx.get("best") or {}
    ok = [a for a, v in stat.items()
          if v.get("status") == "OK" and best.get(a.lower())]
    r7_hits = []
    scanned = 0
    for a in ok:
        b = best[a.lower()]
        body = None
        for p in [os.path.join(b["dir"], b["unit"] + ".cpp")] + \
                glob.glob(os.path.join(b["dir"], "part_*",
                                       b["unit"] + ".cpp")):
            if not os.path.exists(p):
                continue
            for addr2, sig2, body2 in iter_cpp_blocks(p):
                if addr2 == a:
                    body = body2
                    break
            if body is not None:
                break
        if body is None:
            continue
        scanned += 1
        rep = checker.check_function((b.get("emitted") or "").split("::")[0],
                                     body, set(), None)
        n7 = sum(1 for v in rep.violations if v["rule"] == "R7")
        if n7:
            r7_hits.append({"addr": a, "emitted": b.get("emitted"),
                            "r7": n7})
    print("  scanned: %d, R7 flagged: %d" % (scanned, len(r7_hits)))
    for h in r7_hits:
        print("   ", h)

    out = {
        "A_43": {"before_red": red, "after_green": green,
                 "total": len(a_rows), "rows": a_rows},
        "B_602ae0": {"old_r7": len(old_r7), "new_r7": len(new_r7),
                     "bytes_equal": b_bytes == o_bytes,
                     "bytes": len(b_bytes) // 2},
        "C_identity": {"sample": len(c_rows), "drift": drift,
                       "sentinel_units": sentinel, "rows": c_rows},
        "D_regress": {"match": reg_match, "total": len(reg),
                      "rule_viol": reg_viol},
        "E_48ace0": {"free_sig": free_sig,
                     "verdict": id_rep.get("0x48ace0", {}).get("verdict")},
        "F_r7_scan": {"scanned": scanned, "hits": r7_hits},
    }
    dst = os.path.join(AUDIT, "remediation_verify.json")
    with open(dst, "w", encoding="utf-8") as f:
        json.dump(out, f, indent=1, ensure_ascii=False)
    print("wrote", dst)


if __name__ == "__main__":
    main()
